import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = name => path.dirname(require.resolve(`${name}/package.json`));
const dataUrl = file => `data:font/woff2;base64,${fs.readFileSync(file).toString('base64')}`;
const katexDir = packageDir('katex');
const geistDir = packageDir('@fontsource-variable/geist');
const playfairDir = packageDir('@fontsource/playfair-display');

// Metro SDK 57 warns that CSS url(relative-font) is unsupported. Embed only
// WOFF2 from pinned, trusted packages. No learner-authored CSS is processed here.
// All current target Android WebViews support WOFF2; the device gate checks it.
const inlineWoff2 = (css, base) => css.replace(/@font-face\s*\{[^}]*\}/g, face => {
  const woff = face.match(/url\(["']?([^\s)"']+\.woff2)["']?\)/);
  if (!woff) throw new Error('Trusted font-face has no WOFF2 source');
  return face.replace(/src\s*:[^;}]+[;]?/, `src:url("${dataUrl(path.resolve(base, woff[1]))}") format("woff2");`);
});
const fontFace = (family, weight, file, range = '') => `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};src:url("${dataUrl(file)}") format("woff2");${range}}`;
const css = [
  '/*! Generated by scripts/build-reader-assets.mjs. Do not edit or commit. */',
  `/*! KaTeX license: ${fs.readFileSync(path.join(katexDir, 'LICENSE'), 'utf8').replaceAll('*/', '* /')} */`,
  ...[[geistDir, 'Geist'], [playfairDir, 'Playfair Display']].map(([dir, name]) =>
    `/*! ${name}: ${fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').replaceAll('*/', '* /')} */`),
  `/*! Abyssinica SIL: ${fs.readFileSync(path.join(root, 'public/fonts/OFL.txt'), 'utf8').replaceAll('*/', '* /')} */`,
  inlineWoff2(fs.readFileSync(path.join(katexDir, 'dist/katex.min.css'), 'utf8'), path.join(katexDir, 'dist')),
  fontFace('Geist Variable', '100 900', path.join(geistDir, 'files/geist-latin-wght-normal.woff2')),
  ...[400, 700].map(weight => fontFace('Playfair Display', weight, path.join(playfairDir, `files/playfair-display-latin-${weight}-normal.woff2`))),
  fontFace('Abyssinica SIL', 400, path.join(root, 'public/fonts/AbyssinicaSIL-Ethiopic.woff2'), 'unicode-range:U+1200-137F,U+1380-139F,U+2D80-2DDF,U+AB00-AB2F;'),
].join('\n');
const urls = [...css.matchAll(/url\(["']?([^\s)"']+)/g)].map(match => match[1]);
if (!urls.length || urls.some(url => !url.startsWith('data:font/woff2;base64,'))) {
  throw new Error('Reader asset CSS contains an unembedded resource');
}
const output = path.join(root, 'src/reader-core/assets.generated.css');
fs.writeFileSync(output, css + '\n');
console.log(`Reader assets: ${urls.length} embedded WOFF2 faces, ${Buffer.byteLength(css)} bytes (uncompressed CSS).`);
